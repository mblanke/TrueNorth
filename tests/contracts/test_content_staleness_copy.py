"""The worker's copy of the content clock's rules is generated from the API's (ADR 0014,
issue #286; ADR 0002 §5).

The API (Mark reviewed, the feeds' ``flag_stale``) and the worker's hourly sync
(worker/content_review_sync.py) both apply ``app/content_review/staleness.py``; the two images
cannot import each other, so the worker carries a copy, written by
``scripts/export_content_staleness.py``. A drift would mean a review clears one set of
reasons and the next sync puts back another.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "control-plane/api/app/content_review/staleness.py"
COPY_DIR = ROOT / "control-plane/worker/worker/content_review_runtime"
SCRIPT = ROOT / "scripts/export_content_staleness.py"


def test_the_worker_copy_is_the_generated_one():
    done = subprocess.run([sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True, timeout=60)
    assert done.returncode == 0, done.stdout + done.stderr


def test_the_copy_is_the_source_under_a_generated_header():
    copy = (COPY_DIR / "staleness.py").read_text(encoding="utf-8")
    header, _, body = copy.partition("\n")
    assert header.startswith("# GENERATED by scripts/export_content_staleness.py") and "Do not edit" in header
    assert body == SOURCE.read_text(encoding="utf-8")


def test_nothing_else_is_copied():
    assert sorted(p.name for p in COPY_DIR.glob("*.py") if p.name != "__init__.py") == ["staleness.py"]
    assert not (ROOT / "control-plane/worker/worker/content_staleness.py").exists(), "the old hand-made copy"
