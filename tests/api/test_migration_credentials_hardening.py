"""e0f1a2b3c4d5 (ADR 0013 §3): existing ranges keep working and nothing holds a secret it should not.

Upgrade from its parent onto a database holding two ranges, one with an ADR 0012 credential
row (sealed ``tnsec:v1``), and a generated wiki page whose body and earlier revision carry
``{{tn-credential:...}}`` tokens. Then:

* the row is resealed ``tnsec:rc1`` and still opens to the same password;
* every machine without a declared built-in login gets an implicit staff row (generated,
  sealed, not applied, noted "template password still valid"); a lab session's go to its
  Student (``_lab_ranges``, the second test);
* the page is regenerated without credentials or tokens, its notes kept, and no revision
  holds a token any more;

and the downgrade reseals ``tnsec:v1`` (what the code before it reads) and drops the new
columns and table. SQLite here; test_migration_populated_upgrade.py covers PostgreSQL in CI.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import uuid
from pathlib import Path

import pytest
import sqlalchemy as sa

API = Path(__file__).resolve().parents[2] / "control-plane" / "api"
PARENT, REVISION = "d9e0f1a2b3c4", "e0f1a2b3c4d5"
OLD_PW = "Old-Declared-1!"
TEMPLATE = ("name: t\nnodes:\n  - {id: dc01, os: windows-server-2022}\n  - {id: web01, os: ubuntu-2404}\n"
            "  - {id: fw01, os: pfsense}\n")


def _alembic(url: str, *args: str) -> None:
    env = {**os.environ, "DATABASE_URL": url, "PYTHONPATH": str(API), "AUTH_DISABLED": "true"}
    done = subprocess.run([sys.executable, "-m", "alembic", *args], cwd=API, env=env, capture_output=True, text=True,
                          timeout=300)
    assert done.returncode == 0, f"alembic {' '.join(args)} failed:\n{done.stdout[-3000:]}\n{done.stderr[-3000:]}"


def _insert(db, table: str, **values) -> None:
    cols = ", ".join(values)
    db.execute(sa.text(f"INSERT INTO {table} ({cols}) VALUES ({', '.join(':' + c for c in values)})"),
               {k: (str(v) if isinstance(v, uuid.UUID) else v) for k, v in values.items()})


@pytest.mark.slow
def test_upgrade_reseals_adds_staff_logins_and_scrubs_the_wiki(tmp_path):
    from app import secretbox
    from app.range_credentials import seal as rc_seal
    from app.range_credentials import wiki_doc

    url = f"sqlite:///{tmp_path / 'hardening.db'}"
    _alembic(url, "upgrade", PARENT)
    engine = sa.create_engine(url)
    tenant, tmpl, rng, lab_rng, row_id, space, page, user = (uuid.uuid4() for _ in range(8))
    token_body = (f"{wiki_doc.BEGIN}\n| `dc01` | `Administrator` | `{{{{tn-credential:{row_id}}}}}` |\n"
                  f"| `web01` | `ubuntu` | `{{{{tn-credential:template-linux}}}}` |\n{wiki_doc.END}\n\n"
                  "## Notes\n\nKeep this note.\n")
    from app.models import Range, RangeState, Template, Tenant
    from app.models_wiki import WikiPage, WikiRevision, WikiSpace
    from sqlalchemy.orm import Session

    with Session(engine) as db:  # the parent revision's schema is the ORM's for these tables
        db.add(Tenant(id=tenant, name="t", slug="t"))
        db.flush()
        db.add(Template(id=tmpl, name="tp", version="1", yaml=TEMPLATE, tenant_id=tenant))
        db.flush()
        for rid, name in ((rng, "r"), (lab_rng, "lab")):
            db.add(Range(id=rid, name=name, template_id=tmpl, tenant_id=tenant, state=RangeState.ready))
        db.add(WikiSpace(id=space, tenant_id=tenant, name="Ranges", slug="ranges", visibility="staff",
                         system_owned=True))
        db.flush()
        db.add(WikiPage(id=page, tenant_id=tenant, space_id=space, title="r", slug="r", body=token_body,
                        tags=f"range-doc,range:{rng}", author_id=user, last_editor_id=user, revision_number=1))
        db.flush()
        db.add(WikiRevision(tenant_id=tenant, page_id=page, revision_number=1, title="r", body=token_body,
                            editor_id=user, edit_summary="Generated by TrueNorth"))
        db.commit()
    with engine.begin() as db:  # a row as ADR 0012's code wrote it
        _insert(db, "range_credentials", id=row_id, tenant_id=tenant, range_id=rng, machine="dc01",
                username="Administrator", password=secretbox.seal(OLD_PW), generated=0, student_visible=0,
                applied=1, role="admin", notes="")

    _alembic(url, "upgrade", REVISION)
    with engine.connect() as db:
        rows = db.execute(sa.text("SELECT range_id, machine, username, password, source, applied, notes, "
                                  "student_visible FROM range_credentials ORDER BY range_id, machine")).all()
        by = {(str(r[0]), r[1], r[2]): r for r in rows}
        old = by[(str(rng), "dc01", "Administrator")]
        assert old[3].startswith(rc_seal.PREFIX) and rc_seal.unseal(old[3]) == OLD_PW and old[4] == "declared"
        implicit = by[(str(rng), "web01", "ubuntu")]
        assert implicit[4] == "implicit" and not implicit[5] and "template password still valid" in implicit[6]
        assert implicit[3].startswith(rc_seal.PREFIX)
        assert {k for k in by if k[0] == str(lab_rng)} == {(str(lab_rng), "dc01", "Administrator"),
                                                          (str(lab_rng), "web01", "ubuntu")}
        assert not any(k[1] == "fw01" for k in by)  # appliances: none
        body = db.execute(sa.text("SELECT body FROM wiki_pages")).scalar()
        revisions = [b for (b,) in db.execute(sa.text("SELECT body FROM wiki_revisions"))]
    assert "tn-credential" not in body and wiki_doc.is_current(body) and body.rstrip().endswith("Keep this note.")
    assert len(revisions) == 2 and all("tn-credential" not in b for b in revisions)
    plain = [rc_seal.unseal(r[3]) for r in rows]
    for b in [body, *revisions]:
        assert all(p not in b for p in plain)

    _alembic(url, "downgrade", PARENT)
    with engine.connect() as db:
        stored = db.execute(sa.text("SELECT password FROM range_credentials WHERE username = 'Administrator' "
                                    "AND range_id = :r"), {"r": str(rng)}).scalar()
        assert stored.startswith("tnsec:v1:") and secretbox.unseal(stored) == OLD_PW
    insp = sa.inspect(engine)
    assert "range_credential_snapshots" not in insp.get_table_names()
    assert not {"source", "scenario", "rotated_at", "previous_password"} & {
        c["name"] for c in insp.get_columns("range_credentials")}
    _alembic(url, "upgrade", "head")
    engine.dispose()


def test_the_lab_marker_follows_lab_sessions(tmp_path):
    """migrate_0013 hands a lab session's implicit logins to its Student, as new labs' are."""
    from app.range_credentials import migrate_0013

    engine = sa.create_engine(f"sqlite:///{tmp_path / 'labs.db'}")
    with engine.begin() as db:
        db.execute(sa.text("CREATE TABLE lab_sessions (range_id TEXT, retired_ranges TEXT)"))
        a, b = uuid.uuid4(), uuid.uuid4()
        db.execute(sa.text("INSERT INTO lab_sessions VALUES (:a, :r)"), {"a": str(a), "r": json.dumps([str(b)])})
        assert migrate_0013._lab_ranges(db) == {str(a), str(b)}
