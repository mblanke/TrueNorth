"""scripts/export_worker_tables.py: render() emits executable SQLAlchemy Core for exactly
WORKER_TABLES from the API's metadata, --check passes against the committed worker copy
and fails on drift. Nothing is written: only --check mode runs."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

_spec = importlib.util.spec_from_file_location(
    "cov_c_export_worker_tables", ROOT / "scripts" / "export_worker_tables.py"
)
mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mod)


def test_render_defines_every_worker_table_as_executable_core():
    text = mod.render()
    assert text.startswith('"""GENERATED by scripts/export_worker_tables.py')
    assert "metadata = sa.MetaData()" in text
    for tname in mod.WORKER_TABLES:
        assert f"{tname} = sa.Table(" in text

    # The rendered file stands on its own: import it and compare the metadata.
    ns: dict = {}
    exec(compile(text, "tables.py", "exec"), ns)  # noqa: S102 - the script's own output
    assert set(ns["metadata"].tables) == set(mod.WORKER_TABLES)
    users = ns["metadata"].tables["users"]
    assert users.columns["id"].primary_key
    assert ns["GUID"] is not None


def test_check_passes_when_the_committed_worker_copy_matches(monkeypatch):
    monkeypatch.setattr(sys, "argv", ["export_worker_tables.py", "--check"])
    assert mod.main() == 0


def test_check_fails_on_drift(tmp_path, monkeypatch):
    stale = tmp_path / "tables.py"
    stale.write_text("# stale worker copy\n", encoding="utf-8")
    monkeypatch.setattr(mod, "OUT", stale)
    monkeypatch.setattr(sys, "argv", ["export_worker_tables.py", "--check"])
    assert mod.main() == 1
