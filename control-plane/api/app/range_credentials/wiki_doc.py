"""The generated range page (ADR 0012 §14 as amended by ADR 0013 §3): one wiki page per range, staff only.

Written in the tenant's **Ranges** space: the space marked ``system_owned``, created by
the first page (slug ``ranges``, or ``ranges-generated`` when a person's space took that
one). A system-owned space is always staff-only: the wiki router hides it from Students and
observers whatever its ``visibility`` says and refuses to change its visibility (409), and
writing a page puts it back to ``staff`` should it ever differ. The page has two parts:

* a generated block between ``BEGIN`` and ``END``: the range, its machines (OS, template
  and version, addresses), its networks and every account **by name only**: machine,
  username, role, whether Students are handed it, how it was made. No password and no
  token for one is ever written (ADR 0013 §3): staff reveal passwords one at a time on the
  range's credentials panel (``/ranges/{id}``), where each reveal is audited. Rewritten from
  the range, its template and its credential rows each time;
* everything after ``END`` (a ``## Notes`` section to start with), which is the staff's
  own and is kept as it is.

``RENDER_VERSION`` is stamped into the block; pages rendered before it (ADR 0012's, with
``{{tn-credential:...}}`` tokens) are regenerated by the ADR 0013 migration, which also
strips those tokens from their earlier revisions (``strip_legacy_tokens``).

Each change is a new revision, like an edit. A page nobody changed is not rewritten. An
editor's save keeps the stored generated block and takes only what follows ``END`` from the
editor (``keep_generated``).
"""

from __future__ import annotations

import json
import logging
import re
import uuid
from typing import Any

from sqlalchemy import update
from sqlalchemy.orm import Session

from .. import safe_yaml
from ..models import Range
from ..models_wiki import WikiPage, WikiRevision, WikiSpace
from .models import RangeCredential

logger = logging.getLogger("truenorth.range_credentials.wiki")

SPACE_SLUG = "ranges"
SPACE_SLUG_FALLBACK = "ranges-generated"
SPACE_NAME = "Ranges"
SPACE_DESCRIPTION = ("Generated range documentation: machines, networks and account names (no passwords). "
                     "Staff only, managed by TrueNorth. Write under each page's Notes heading.")
GENERATED_TAG = "range-doc"
BEGIN = "<!-- tn:range-doc:begin (generated by TrueNorth; everything up to the end marker is rewritten) -->"
END = "<!-- tn:range-doc:end (write below this line; it is kept) -->"
NOTES_HEADING = "## Notes"
# 2: ADR 0013 §3, account names only. 1 (unstamped): ADR 0012, credential tokens.
RENDER_VERSION = 2
VERSION_MARK = f"<!-- tn:range-doc:version {RENDER_VERSION} -->"
# The tokens version 1 wrote (a credential row's id, or a template build login), and what
# ``strip_legacy_tokens`` puts in their place.
LEGACY_TOKEN_RE = re.compile(r"\{\{tn-credential:([0-9a-fA-F-]{36}|template-windows|template-linux)\}\}")
LEGACY_TOKEN_REPLACEMENT = "(removed: see the range's credentials panel)"
DEFAULT_NOTES = f"{NOTES_HEADING}\n\n_Hand-written notes about this range go here. They are kept when the page is regenerated._\n"


def range_tag(rng: Range) -> str:
    return f"range:{rng.id}"


# ── Space ───────────────────────────────────────────────────────────────
def system_space(db: Session, tenant_id: uuid.UUID, actor: uuid.UUID) -> WikiSpace:
    """The tenant's system-owned Ranges space, created if missing; always staff-only."""
    space = (
        db.query(WikiSpace)
        .filter(WikiSpace.tenant_id == tenant_id, WikiSpace.system_owned.is_(True))
        .order_by(WikiSpace.created_at)
        .first()
    )
    if space is None:
        taken = {slug for (slug,) in db.query(WikiSpace.slug).filter(
            WikiSpace.tenant_id == tenant_id, WikiSpace.slug.in_([SPACE_SLUG, SPACE_SLUG_FALLBACK]))}
        slug = next((s for s in (SPACE_SLUG, SPACE_SLUG_FALLBACK) if s not in taken),
                    f"{SPACE_SLUG}-{uuid.uuid4().hex[:8]}")
        space = WikiSpace(tenant_id=tenant_id, name=SPACE_NAME, slug=slug, description=SPACE_DESCRIPTION,
                          icon="dns", visibility="staff", is_archived=False, created_by=actor, system_owned=True)
        db.add(space)
        db.flush()
    elif space.visibility != "staff" or space.deleted_at is not None:
        space.visibility, space.deleted_at = "staff", None  # the flag decides, not the column
    return space


def _page(db: Session, space: WikiSpace, rng: Range) -> WikiPage | None:
    return (
        db.query(WikiPage)
        .filter(WikiPage.space_id == space.id, WikiPage.tenant_id == space.tenant_id,
                WikiPage.deleted_at.is_(None), WikiPage.tags.contains(range_tag(rng)))
        .order_by(WikiPage.created_at)
        .first()
    )


# ── Upsert / retire ─────────────────────────────────────────────────────
def upsert(db: Session, rng: Range, rows: list[RangeCredential], actor: uuid.UUID) -> WikiPage | None:
    """Create or regenerate the range's page. Does not commit. None when a concurrent save
    won (the next change regenerates)."""
    # every read before any write
    generated = render(rng, rows, template_doc(db, rng))
    space = system_space(db, rng.tenant_id, actor)
    title = (rng.name or str(rng.id))[:500]
    page = _page(db, space, rng)
    if page is None:
        page = WikiPage(
            tenant_id=space.tenant_id, space_id=space.id, parent_id=None, title=title, slug=_slugify(title),
            body=compose(generated, DEFAULT_NOTES), tags=f"{GENERATED_TAG},{range_tag(rng)}", is_published=True,
            ordinal=0, author_id=actor, last_editor_id=actor, revision_number=1,
        )
        db.add(page)
        db.flush()
        _revision(db, page, actor, "Generated by TrueNorth")
        return page
    body = compose(generated, notes_of(page.body or ""))
    if body == page.body and title == page.title:
        return page
    seen = page.revision_number
    moved = db.execute(
        update(WikiPage)
        .where(WikiPage.id == page.id, WikiPage.revision_number == seen)
        .values(revision_number=seen + 1, body=body, title=title, slug=_slugify(title), last_editor_id=actor)
        .execution_options(synchronize_session=False)
    ).rowcount
    if moved != 1:
        return None
    db.refresh(page)
    _revision(db, page, actor, "Regenerated by TrueNorth")
    return page


def retire(db: Session, rng: Range) -> None:
    """Soft-delete the range's page (the range record is being deleted). Neither it nor its
    revisions hold a password or a token for one."""
    space = (
        db.query(WikiSpace)
        .filter(WikiSpace.tenant_id == rng.tenant_id, WikiSpace.system_owned.is_(True))
        .first()
    )
    if space is not None and (page := _page(db, space, rng)) is not None:
        page.soft_delete()


# ── Reading and editing (routers/wiki.py) ────────────────────────────────
def is_generated(page: WikiPage, space: WikiSpace) -> bool:
    return bool(space.system_owned) and GENERATED_TAG in (page.tags or "").split(",")


def range_of(page: WikiPage) -> uuid.UUID | None:
    for tag in (page.tags or "").split(","):
        if tag.startswith("range:"):
            try:
                return uuid.UUID(tag[6:])
            except ValueError:
                return None
    return None


def strip_legacy_tokens(body: str | None) -> str:
    """``body`` without ADR 0012's credential tokens (each replaced by a pointer to the
    credentials panel). For the ADR 0013 migration of earlier pages and revisions."""
    return LEGACY_TOKEN_RE.sub(LEGACY_TOKEN_REPLACEMENT, body or "")


def is_current(body: str | None) -> bool:
    """Whether a generated page was rendered by this ``RENDER_VERSION``."""
    return VERSION_MARK in (body or "")


def keep_generated(stored: str, submitted: str) -> str:
    """An editor's save of a generated page: the stored generated block, then the editor's
    own part (``notes_of``). Whatever the editor typed into the block is not stored."""
    block = stored.split(END, 1)[0] if END in stored else ""
    generated = block.split(BEGIN, 1)[1] if BEGIN in block else block
    return compose(generated.strip("\n"), notes_of(submitted or ""))


def _revision(db: Session, page: WikiPage, actor: uuid.UUID, summary: str) -> None:
    db.add(WikiRevision(tenant_id=page.tenant_id, page_id=page.id, revision_number=page.revision_number,
                        title=page.title, body=page.body, editor_id=actor, edit_summary=summary))
    db.flush()


# ── Body ────────────────────────────────────────────────────────────────
def compose(generated: str, notes: str) -> str:
    return f"{BEGIN}\n{generated.rstrip()}\n{END}\n\n{notes.strip()}\n"


def notes_of(body: str) -> str:
    """The part of a page that is the staff's own: after the end marker; without one (a
    hand edit removed it), from the ``## Notes`` heading on; else the default notes.
    Earlier content stays in the page's revisions."""
    if END in body:
        return body.split(END, 1)[1].strip() or DEFAULT_NOTES
    match = re.search(rf"^{re.escape(NOTES_HEADING)}\s*$", body, flags=re.MULTILINE)
    return body[match.start():].strip() if match else DEFAULT_NOTES


def _cell(value: Any) -> str:
    text = "" if value is None else str(value)
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()


def _code(value: str) -> str:
    fence = "``" if "`" in value else "`"
    pad = " " if value.startswith("`") or value.endswith("`") else ""
    return f"{fence}{pad}{value.replace('|', chr(92) + '|')}{pad}{fence}"


def template_doc(db: Session, rng: Range) -> dict[str, Any]:
    from .service import template_of

    tmpl = template_of(db, rng)
    try:
        doc = safe_yaml.load(tmpl.yaml or "") if tmpl else {}
    except Exception:  # noqa: BLE001 — an unreadable template documents as empty
        doc = {}
    doc = doc if isinstance(doc, dict) else {}
    doc["_tn_template"] = {"name": tmpl.name if tmpl else "", "version": tmpl.version if tmpl else ""}
    return doc


def _built(rng: Range) -> dict[str, dict[str, Any]]:
    """node id -> what the last build recorded for it (provisioner_output["vms"])."""
    try:
        out = json.loads(rng.provisioner_output or "{}")
    except ValueError:
        return {}
    vms = out.get("vms") if isinstance(out, dict) else None
    prefix = f"{str(rng.id)[:8]}-"
    built: dict[str, dict[str, Any]] = {}
    for vm in vms if isinstance(vms, list) else []:
        if not isinstance(vm, dict):
            continue
        node = str(vm.get("node_id") or str(vm.get("name") or "").removeprefix(prefix))
        built.setdefault(node, vm)
    return built


def _addresses(vm: dict[str, Any] | None, planned: str) -> str:
    if not vm:
        return f"{planned} (planned)" if planned else "—"
    ips = [n.get("ip") for n in vm.get("nics") or [] if isinstance(n, dict) and n.get("ip")]
    ips = ips or ([vm["ip"]] if vm.get("ip") else [])
    return ", ".join(dict.fromkeys(str(i) for i in ips)) or "—"


def render(rng: Range, rows: list[RangeCredential], doc: dict[str, Any]) -> str:
    tmpl = doc.get("_tn_template") or {}
    built = _built(rng)
    lines = [
        VERSION_MARK,
        f"# {_cell(rng.name)}",
        "",
        "> **Staff only.** Generated by TrueNorth from the range, its template and its accounts. This page "
        f"holds no passwords: reveal them one at a time on the range's [credentials panel](/ranges/{rng.id}) "
        "(each reveal is recorded in the audit log). Students see the accounts handed to them on their own "
        "lab or exercise page.",
        "",
        "| | |",
        "|---|---|",
        f"| Range | {_cell(rng.name)} (`{rng.id}`) |",
        f"| State | {_cell(getattr(rng.state, 'value', rng.state))} |",
        f"| Template | {_cell(tmpl.get('name'))} {_cell(tmpl.get('version'))} |",
        f"| Built on | {_cell(rng.provisioner_backend)} |",
        "",
        "## Machines",
        "",
    ]
    nodes = [n for n in doc.get("nodes") or [] if isinstance(n, dict)]
    if nodes:
        lines += ["| Machine | Name | Role | OS | Built from | Addresses |", "|---|---|---|---|---|---|"]
        for n in nodes:
            nid = str(n.get("id") or "")
            vm = built.get(nid)
            source = (vm or {}).get("template") or (vm or {}).get("template_name") or ""
            lines.append(
                f"| `{_cell(nid)}` | {_cell(n.get('name'))} | {_cell(n.get('role'))} | {_cell(n.get('os'))} | "
                f"{_cell(source) or '—'} | {_cell(_addresses(vm, str(n.get('ip') or '')))} |"
            )
    elif doc.get("assets"):
        lines += ["| Machine | Type | Count |", "|---|---|---|"]
        for a in doc["assets"]:
            if isinstance(a, dict):
                lines.append(f"| `{_cell(a.get('role'))}` | {_cell(a.get('type'))} | {_cell(a.get('count'))} |")
    else:
        lines.append("_The template declares no machines._")
    lines += ["", "## Networks", ""]
    network = doc.get("network") if isinstance(doc.get("network"), dict) else {}
    vlans = [v for v in network.get("vlans") or [] if isinstance(v, dict)]
    if vlans:
        lines += ["| Network | VLAN | CIDR | Description |", "|---|---|---|---|"]
        lines += [f"| {_cell(v.get('name'))} | {_cell(v.get('id'))} | {_cell(v.get('cidr'))} | "
                  f"{_cell(v.get('description'))} |" for v in vlans]
    else:
        lines.append("_The template declares no networks._")
    lines += ["", "## Accounts", "",
              f"Passwords are on the range's [credentials panel](/ranges/{rng.id}), never in this page.", ""]
    if rows:
        lines += ["| Machine | Username | Role | Password | Set at deploy | Handed to Students | Notes |",
                  "|---|---|---|---|---|---|---|"]
        from . import service as _service
        pending = _service.setup_pending_machines(rng)
        for r in rows:
            applied = ("yes" if r.applied else "_being set up_" if r.machine in pending
                       else "**not set by TrueNorth**")
            lines.append(
                f"| `{_cell(r.machine)}` | {_code(r.username)} | {_cell(r.role)} | {_kind(r)} | {applied} | "
                f"{'yes' if r.student_visible else 'no'} | {_cell(r.notes)} |"
            )
    else:
        lines.append("_No accounts: the range's machines are appliances, which keep the login of their own "
                     "configuration._")
    return "\n".join(lines) + "\n"


def _kind(row: RangeCredential) -> str:
    """How the account's password was made, without the password."""
    if row.scenario:
        return "typed in (scenario, authored by design)"
    if row.source == "implicit":
        return "generated (staff login)"
    return "generated" if row.generated else "typed in"


def _slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return (slug or "page")[:200]
