"""Turn an exercise scenario into a range definition.

Scenario contract (align with the exercise scenario builder; TBD with owner):

scenario:
  id: SCN-0001
  title: Phishing to domain compromise
  techniques: [T1566.001, T1059.001, T1003.001]
  assets:
    - {role: domain_controller, count: 1}
    - {role: workstation, count: 5}
    - {role: web_server, count: 1}
    - {role: attacker, count: 1}

Roles map to blueprints through config/role_map.yml. A core router joining every
network is always added when there is more than one network.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from .common import RANGE_ID_RE, RangeError, load_yaml
from .compose import load_blueprint


def scenario_to_range(root: Path, scenario_file: Path, range_id: str, expires: str,
                      owner: str = "TBD", students: int = 1) -> dict:
    if not RANGE_ID_RE.match(range_id):
        raise RangeError(f"range id must match {RANGE_ID_RE.pattern}")
    doc = load_yaml(scenario_file)
    sc = doc.get("scenario") if isinstance(doc, dict) else None
    if not isinstance(sc, dict) or not isinstance(sc.get("assets"), list):
        raise RangeError(f"{scenario_file}: needs scenario.assets (list)")
    role_map = (load_yaml(root / "config" / "role_map.yml").get("roles") or {})

    uses: dict[tuple[str, str], dict] = {}
    unmapped = []
    for a in sc["assets"]:
        role = a.get("role")
        count = a.get("count", 1)
        m = role_map.get(role)
        if m is None:
            unmapped.append(str(role))
            continue
        key = (m["blueprint"], m["as"])
        u = uses.setdefault(key, {"blueprint": m["blueprint"], "as": m["as"], "params": {}})
        if m.get("count_param"):
            u["params"][m["count_param"]] = u["params"].get(m["count_param"], 0) + int(count)
    if unmapped:
        raise RangeError(f"roles not in config/role_map.yml: {', '.join(sorted(set(unmapped)))}")

    # Blueprints with a count param that the scenario did not mention keep their default,
    # except counts that would add unrequested hosts: force them to their minimum.
    for (bp_name, alias), u in uses.items():
        spec = load_blueprint(root, bp_name)["blueprint"].get("params", {}) or {}
        for p, s in spec.items():
            if s.get("type") == "int" and p not in u["params"] and "min" in s:
                u["params"][p] = s["min"]

    routed = []
    for (bp_name, alias), u in uses.items():
        if bp_name == "core_router":
            continue
        for n in load_blueprint(root, bp_name).get("networks", []) or []:
            routed.append(f"@{alias}-{n['name']}")
    use_list = [u for k, u in sorted(uses.items()) if k[0] != "core_router"]
    if len(routed) > 1:
        use_list.append({"blueprint": "core_router", "as": "core", "params": {"routed_networks": routed}})

    probe = None
    for u in use_list:
        if u["blueprint"] == "attacker_enclave":
            probe = f"{u['as']}-op01"
    if probe is None:
        raise RangeError("scenario has no attacker asset; add one so isolation can be probed from inside")

    return {
        "range": {
            "id": range_id,
            "owner": owner,
            "exercise": sc.get("title", sc.get("id", "TBD")),
            "expires": expires,
            "students": students,
            "description": f"Generated from scenario {sc.get('id')}",
        },
        "use": use_list,
        "validation": {"probe_vm": probe, "checks": ["isolation", "connectivity"]},
        "integrations": {"arc2": {"enabled": False, "profile": str(sc.get("id", "TBD"))}},
        "source_scenario": {
            "id": sc.get("id"),
            "title": sc.get("title"),
            "techniques": sc.get("techniques", []),
            "file": scenario_file.name,
        },
        "power_after_build": "poweredon",
    }


def dump(doc: dict) -> str:
    header = ("# Generated by `tools/range scenario`. Review before compiling.\n"
              "# Edit freely; regenerate only if the scenario changes.\n")
    return header + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)
