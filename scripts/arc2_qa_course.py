#!/usr/bin/env python3
"""Run ARC²'s QA stage over an existing course file and its instructor pack, with no model call.

    python scripts/arc2_qa_course.py content/courses/c103-intro-to-networking.yaml
    python scripts/arc2_qa_course.py <course.yaml> --pack <instructor.yaml> --out build/arc2-qa/c103

TAZ drafts courses without ARC²: a course YAML plus a staff-only pack in
``content/courses/instructor/``. This adapts the two into the staging layout ARC²'s QA reads
(``02-content/``, ``04-artifacts/instructor/``, ``05-sensor/``, an adapter ``manifest.json``),
runs ARC²'s own code on it (``arc2.qa``, ``arc2.check``; imported, never copied or changed),
adds the lab and instructor-pack checks a TAZ course needs, and writes

    <out>/06-qa/report.md     ARC²'s report: preview digest, objectives, findings, human actions, verdict
    <out>/06-qa/report.json   the same, machine-readable

Every ARC² check is accounted for in the report as ``ran``, ``not_applicable`` (with the reason,
for artefacts a TAZ course does not produce: cmi5 package, learner HTML pages, inject timeline,
sensor map) or ``not_run`` (it applies but could not run, with the reason). Nothing passes or
fails silently. Exit 0 when no finding blocks, 1 when one does, 2 on bad arguments.

Severities: ``fail`` blocks; ``human`` is an open action for a person; ``advisory`` is information,
including ``lab.needs_range_support`` (setup the range must be changed to provide: file a ticket).
No network, no model, nothing written outside ``--out``.
"""

