REPORT_SCHEMA = "arc2-qa-existing/1"
DEFAULT_OUT = Path("build/arc2-qa")
REGISTER_REL = Path("content/catalogue/production_register.csv")
NA_TAZ = "not applicable (TAZ course)"
FAIL, HUMAN, ADVISORY = "fail", "human", "advisory"
AUTHOR, PACK_AUTHOR, ORCH = "course-author", "pack-author", "orchestrator"

NRS_MARKER = re.compile(r"needs?\s+range\s+support\s*[:\-\u2013\u2014]?\s*([^.;\n]+)", re.I)
# What a lab step can assume that a stock range template does not hold. (label, text pattern,
# stem the lab_setup must mention for the need to count as handled)
SETUP_NEEDS: tuple[tuple[str, re.Pattern[str], re.Pattern[str]], ...] = (
    (
        "spare disk",
        re.compile(r"\b(spare|extra|additional|second|unused|blank)\s+(virtual\s+)?(disk|drive|volume)s?\b", re.I),
        re.compile(r"disk|drive|volume", re.I),
    ),
    (
        "decoy or planted item",
        re.compile(r"\b(decoy|dummy|planted|seeded)\s+(process|file|service|account|user|task)\w*", re.I),
        re.compile(r"decoy|dummy|planted|seeded", re.I),
    ),
    (
        "extra users",
        re.compile(r"\b(extra|additional|spare|new|second)\s+(user|account)s?\b", re.I),
        re.compile(r"user|account", re.I),
    ),
)
ANSWER_CITE = re.compile(r"\bQ(\d+)\b\s*[:.\-\u2013]?\s*\(?\s*([A-D])\b")

# ARC² checks that cannot apply to a TAZ-shaped course, and why. id -> reason.
NOT_APPLICABLE: dict[str, str] = {
    "schema.*": "no ARC² run manifest: a TAZ course is a course YAML plus an instructor pack; the course file is validated against course-content.schema.json by taz.schema",
    "stage.*": "no seven-stage run: nothing was generated by ARC² stages",
    "activities.*": "ARC² activity declarations live in the blueprint outline; a TAZ course has no outline gate",
    "range.evidence": "needs critical events, inject timeline, new range template and lab profile; a TAZ lab is Student-run steps on an existing template (lab.* checks cover it)",
    "lab_profile.*": "ARC² range-engineer artefact; a TAZ course reuses an existing range template",
    "trace.file_*": "no files[] ledger or sha256 stamps: no staged ARC² artefacts to trace",
    "trace.validator_* / trace.ce_* / trace.inject_* / trace.summative_*": "no validators, critical events or injects: a TAZ course has no sensor stage",
    "trace.xapi_*": "no telemetry map: a TAZ course has no sensor stage",
    "captures.*": "no pre-captured pcap artefacts",
    "gate.*": "no outline or preview gate: acceptance is Standards and SME sign-off (open human action)",
    "cmi5.*": "no cmi5 package: a TAZ course has no learner HTML pages or AU structure (package-builder stage not run)",
    "qa.catalogue_*": "no blueprint catalogue_row.csv; qa.catalogue_identity covers the existing-course case",
    "qa.timeline_* / qa.author_required_marker": "no inject timeline: a TAZ lab has no pre-captured inject schedule",
    "qa.course.arc2_code": "rule expects ARC2-<code>; a TAZ course keeps its catalogue code",
    "qa.course_code_mismatch / qa.course_manifest_mismatch / qa.course_objectives_verbatim": "compare the course file with an ARC² blueprint; the adapter manifest is derived from the file, so the comparison would be vacuous",
}


# ── data ────────────────────────────────────────────────────────────────


@dataclass
class Ledger:
    """Which checks ran, which do not apply, which could not run. Never a silent pass."""

    rows: dict[str, dict[str, Any]] = field(default_factory=dict)

    def ran(self, check_id: str, source: str, what: str) -> None:
        self.rows[check_id] = {"id": check_id, "source": source, "status": "ran", "reason": what}

    def not_applicable(self, check_id: str, source: str, reason: str) -> None:
        self.rows[check_id] = {"id": check_id, "source": source, "status": "not_applicable", "reason": reason}

    def not_run(self, check_id: str, source: str, reason: str) -> None:
        self.rows[check_id] = {"id": check_id, "source": source, "status": "not_run", "reason": reason}


def finding(
    check: str, severity: str, message: str, owner: str, path: str | None = None, module: int | None = None
) -> dict[str, Any]:
    return {
        "check": check,
        "severity": severity,
        "owner_stage": owner,
        "message": message,
        "path": path,
        "module": module,
    }


def _module_of(message: str) -> int | None:
    m = re.search(r"\bmodule (\d+)", message)
    return int(m.group(1)) if m else None


def _load(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def catalogue_code_for(root: Path, course: Path, course_code: str) -> str:
    """The catalogue code of an existing course: its production-register row, else its own code."""
    try:
        with (root / REGISTER_REL).open(newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                if row.get("course_yaml") == course.name and row.get("catalogue_code"):
                    return row["catalogue_code"].strip()
    except OSError:
        pass
    return course_code


# ── adapter: course + pack -> the layout ARC² QA reads ───────────────────


def adapt(
    course: Path, pack: Path | None, out: Path, parsed: dict[str, Any], catalogue_code: str, root: Path
) -> dict[str, Any]:
    """Stage the files and return the adapter manifest (the keys ``arc2.qa`` and ``arc2.check`` read).

    It is deliberately not an ARC² run manifest (no stages, gates or files ledger) and is not
    validated against manifest.schema.json: it exists so ARC²'s own functions can be called."""
    for sub in ("02-content", "04-artifacts", "05-sensor", "06-qa"):
        shutil.rmtree(out / sub, ignore_errors=True)
    (out / "02-content").mkdir(parents=True, exist_ok=True)
    (out / "06-qa").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(course, out / "02-content" / course.name)
    if pack is not None and pack.is_file():
        (out / "04-artifacts" / "instructor").mkdir(parents=True, exist_ok=True)
        shutil.copyfile(pack, out / "04-artifacts" / "instructor" / pack.name)

    modules, objectives = [], []
    for m in parsed["modules"]:
        mid = f"mod_{m['ordinal']:03d}"
        oids = [f"M{m['ordinal']:02d}-O{i:02d}" for i in range(1, len(m["objectives"]) + 1)]
        quiz = {"pass_threshold": m["quiz_pass"], "question_count": len(m["questions"])} if m["questions"] else None
        activity: dict[str, Any] = {"kind": m["activity"]}
        if m["activity"] != "range":
            activity["no_range_reason"] = "declared in the course file"
        modules.append(
            {
                "id": mid,
                "ordinal": m["ordinal"],
                "title": m["title"],
                "objective_ids": oids,
                "is_required": m["is_required"],
                "pass_threshold": m["pass_threshold"],
                "quiz": quiz,
                "activity": activity,
            }
        )
        objectives.extend(
            {"id": oid, "module_id": mid, "text": str(t).strip(), "source": "objective", "po": m["po"]}
            for oid, t in zip(oids, m["objectives"], strict=False)
        )
    manifest: dict[str, Any] = {
        "adapter": "arc2_qa_course: not an ARC2 run manifest; the keys arc2.qa and arc2.check read",
        "course": {
            "code": parsed["course_code"],
            "catalogue_code": catalogue_code,
            "title": parsed["title"],
            "po": None,
            "po_candidates": [],
        },
        "objectives": objectives,
        "content": {"course_yaml": f"02-content/{course.name}", "modules": modules},
    }
    scenarios = sorted(
        {str(m["lab_range"]["scenario"]) for m in parsed["modules"] if (m["lab_range"] or {}).get("scenario")}
    )
    for sid in scenarios:
        src = root / "content" / "scenarios" / sid / "scenario.yaml"
        if src.is_file():
            dest = out / "05-sensor" / sid
            dest.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest / "scenario.yaml")
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


# ── ARC² checks, called not copied ───────────────────────────────────────


def is_upskilling(code: str) -> bool:
    """C500 and up: the self-paced upskilling catalogue, outside the DP1/DP2 programme."""
    digits = "".join(ch for ch in str(code) if ch.isdigit())
    return bool(digits) and int(digits) >= 500 and not str(code).upper().startswith("RMC")


def run_arc2(
    out: Path, manifest: dict[str, Any], raw: dict[str, Any], parsed: dict[str, Any], root: Path, ledger: Ledger
) -> list[dict[str, Any]]:
    out_f: list[dict[str, Any]] = []
    rel = manifest["content"]["course_yaml"]
    api, why = arc2_qa._api()

    if api is None:
        msg = f"the API parsers could not be imported ({why}); course, catalogue and engine rules did not run"
        out_f.append(finding("qa.api_unavailable", HUMAN, msg, ORCH))
        for cid in ("qa.course.*", "qa.catalogue_identity", "qa.engine_scenario"):
            ledger.not_run(cid, "arc2", "the API parsers could not be imported")
    else:
        dropped = {
            "qa.course.arc2_code",
            "qa.course_code_mismatch",
            "qa.course_manifest_mismatch",
            "qa.course_objectives_verbatim",
        }
        upskilling = is_upskilling(manifest["course"]["catalogue_code"])
        if upskilling:
            # Upskilling courses (C500 and up) sit outside the DP1/DP2 programme: no qualification
            # mapping to propose, so qsp_code is optional (it must still be valid when present) and
            # the "proposed, not standards-validated" note does not apply.
            dropped |= {"qa.course.notes_proposed"}
            if raw.get("qsp_code") is None:
                dropped |= {"qa.course.qsp_code"}
        course_f = [f for f in arc2_qa.check_course(out, manifest, root, api) if f["check"] not in dropped]
        out_f += course_f
        ledger.ran(
            "qa.course.*",
            "arc2",
            "arc2.qa.check_course: publication, provenance, status, qsp_code, notes, modules, labs, refs, quiz shape, duplicate stems, miscited sources",
        )
        if upskilling:
            ledger.not_applicable(
                "qa.catalogue_identity",
                "arc2",
                f"{NA_TAZ}: upskilling courses (C500 and up) are not rows of the DP1/DP2 programme catalogue",
            )
        else:
            out_f += arc2_qa.check_catalogue_identity(manifest, root, api)
            ledger.ran(
                "qa.catalogue_identity",
                "arc2",
                f"arc2.qa.check_catalogue_identity: {manifest['course']['catalogue_code']!r} is a course in the catalogue",
            )
        scenario_ids = sorted(p.parent.name for p in (out / "05-sensor").glob("*/scenario.yaml"))
        if scenario_ids:
            for sid in scenario_ids:
                m2 = {
                    "scenario": {"path": f"05-sensor/{sid}/scenario.yaml", "engine_validate": {"status": "unverified"}}
                }
                out_f += arc2_qa.check_engine_scenario(out, m2, api)
            ledger.ran("qa.engine_scenario", "arc2", f"arc2.qa.check_engine_scenario on {', '.join(scenario_ids)}")
        else:
            ledger.not_applicable("qa.engine_scenario", "arc2", f"{NA_TAZ}: no lab_range names a scenario")

    # objective wording and objective-to-content tracing: the one place ARC²'s trace.* applies.
    trace_m = {
        "objectives": manifest["objectives"],
        "content": manifest["content"],
        "files": [
            {
                "path": rel,
                "kind": "content",
                "stage": "code-generator",
                "objective_ids": [o["id"] for o in manifest["objectives"]],
            }
        ],
    }
    out_f += [
        finding(
            f.check, f.severity, f.message, f.owner_stage, rel, _module_of(f.message) or _objective_module(f.message)
        )
        for f in arc2_check._check_trace(trace_m)
    ]
    ledger.ran(
        "objective.observable_verb",
        "arc2",
        "arc2.check._check_trace: no objective opens with understand, be aware, appreciate, know",
    )
    ledger.ran(
        "trace.objective_has_content / trace.module_objectives_resolve",
        "arc2",
        "arc2.check._check_trace: every objective sits in a module of the course file",
    )

    own = Path(rel).name
    po_m = {"course": manifest["course"], "objectives": manifest["objectives"], "critical_events": []}
    po_f = []
    for f in arc2_check._check_po(po_m, root):
        if f.check == "po.bound_claimed" and f"delivered by {own}" in f.message:
            continue  # the course is the claimant, not a rival
        po_f.append(finding(f.check, f.severity, f.message, f.owner_stage, rel))
    out_f += po_f
    ledger.ran(
        "po.*",
        "arc2",
        "arc2.check._check_po: bound POs exist in the crosswalk, may be bound, and are not claimed by another course",
    )

    out_f += [{**f, "module": _module_of(f["message"])} for f in arc2_qa.check_defang(out) if f["check"] == "qa.defang"]
    ledger.ran(
        "qa.defang", "arc2", "arc2.qa.check_defang over the course file and the instructor pack: no offensive artefacts"
    )

    for cid, reason in NOT_APPLICABLE.items():
        ledger.not_applicable(cid, "arc2", f"{NA_TAZ}: {reason}")
    return out_f


def _objective_module(message: str) -> int | None:
    m = re.match(r"M(\d+)-O\d+", message)
    return int(m.group(1)) if m else None


# ── TAZ-kit checks (scripts/check_course.py) ─────────────────────────────


def run_taz(
    course: Path, root: Path, doc: dict[str, Any], text: str, pack: Path | None, held: bool, ledger: Ledger
) -> list[dict[str, Any]]:
    out_f: list[dict[str, Any]] = []

    def record(check_id: str, problems: list[str], what: str) -> None:
        ledger.ran(f"taz.{check_id}", "taz-kit", what)
        for p in problems:
            out_f.append(finding(f"taz.{check_id}", FAIL, p, AUTHOR, course.name, _module_of(p)))

    if held:
        is_held = course.name in cc.HELD_FILES or doc.get("course_code") in cc.HELD_CODES
        record(
            "held",
            [f"{doc.get('course_code')} is held for cleared authors; TAZ does not draft it"] if is_held else [],
            "not one of the seven courses held for cleared authors",
        )
    # the schema check takes the repo-relative course schema, so the root only matters for the lab checks
    record(
        "schema",
        cc._schema_errors(cc.COURSE_SCHEMA, doc),
        "validates against docs/interfaces/course-content.schema.json",
    )
    record("readiness", cc.check_readiness(doc, None), "readiness is set and is not sme_signed")
    record("banner", cc.check_banner(text, doc, None), "provenance banner, provenance unsourced, unpublished note kept")
    waived = {m.get("ordinal") for m in cc._modules(doc) if m.get("activity") in ("theory", "practical")}
    modules_p = [
        p
        for p in cc.check_modules(doc)
        if not (_module_of(p) in waived and (p.endswith("no lab brief") or p.endswith("no lab_range")))
    ]
    record(
        "modules",
        modules_p,
        "six modules, each with objectives, topics, and a lab brief and lab_range unless declared theory or practical",
    )
    record(
        "lab_range", cc.check_lab_range(root, doc), "template and scenario resolve; scenario runs on the same template"
    )
    record("refs", cc.check_refs(root, doc), "every ref is in content/catalogue/references.yaml")
    record("quiz", cc.check_quiz(doc), "five questions, four lettered options, answer A-D, no repeated stem")
    record(
        "quiz_terms",
        cc.check_quiz_terms(doc),
        "HEURISTIC: each question shares a key term with its module's objectives or topics",
    )
    ledger.not_applicable(
        "taz.hosts",
        "taz-kit",
        "superseded by lab.hosts_in_template, which reports the same rule with the hosts verified",
    )
    return out_f


# ── lab checks ───────────────────────────────────────────────────────────


def run_lab(
    parsed: dict[str, Any], root: Path, pack_doc: dict[str, Any] | None, rel: str, ledger: Ledger
) -> tuple[list[dict[str, Any]], dict[str, list[str]], list[dict[str, Any]]]:
    out_f: list[dict[str, Any]] = []
    verified: dict[str, set[str]] = {}
    needs: list[dict[str, Any]] = []
    setups: dict[int, str] = {}
    for e in (pack_doc or {}).get("lab_setup") or []:
        if isinstance(e, dict) and isinstance(e.get("module"), int):
            setups[e["module"]] = f"{setups.get(e['module'], '')} {e.get('setup') or ''}".strip()

    labs = [m for m in parsed["modules"] if m["lab_range"]]
    if not labs:
        for cid in ("lab.hosts_in_template", "lab.host_used", "lab.needs_range_support"):
            ledger.not_applicable(cid, "harness", f"{NA_TAZ}: no module has a lab_range")
        return out_f, {}, needs

    for m in labs:
        n, lr = m["ordinal"], m["lab_range"]
        template = str(lr.get("template") or "")
        nodes = cc.template_nodes(root, template)
        steps = lr.get("steps") or []
        touched: set[str] = set()
        for i, step in enumerate(steps, start=1):
            where = f"module {n} step {i}"
            if not isinstance(step, dict) or not step.get("hosts") or not str(step.get("action") or "").strip():
                out_f.append(
                    finding(
                        "lab.step_shape", FAIL, f"{where}: needs a non-empty hosts list and an action", AUTHOR, rel, n
                    )
                )
                continue
            action = str(step["action"])
            hosts = [str(h) for h in step["hosts"]]
            if nodes is not None:
                for h in hosts:
                    if h in nodes:
                        verified.setdefault(template, set()).add(h)
                    else:
                        out_f.append(
                            finding(
                                "lab.hosts_in_template",
                                FAIL,
                                f"{where}: host {h!r} is not a node of {template!r}",
                                AUTHOR,
                                rel,
                                n,
                            )
                        )
                for tok in cc.HOST_SHAPE.findall(action):
                    if tok not in nodes and tok not in cc.NOT_HOSTS:
                        out_f.append(
                            finding(
                                "lab.hosts_in_template",
                                FAIL,
                                f"{where}: action names {tok!r}, which is not a node of {template!r}",
                                AUTHOR,
                                rel,
                                n,
                            )
                        )
            mentioned = {h for h in hosts if re.search(rf"(?<![\w-]){re.escape(h)}(?![\w-])", action)}
            for h in hosts:
                if h not in mentioned and h not in touched:
                    out_f.append(
                        finding(
                            "lab.host_used",
                            FAIL,
                            f"{where}: lists host {h!r} but no action text touches it, here or in an earlier step",
                            AUTHOR,
                            rel,
                            n,
                        )
                    )
            if nodes is not None:
                for h in sorted(nodes):
                    if h not in hosts and re.search(rf"(?<![\w-]){re.escape(h)}(?![\w-])", action):
                        out_f.append(
                            finding(
                                "lab.host_unlisted",
                                ADVISORY,
                                f"{where}: the action names {h!r} but the step does not list it in hosts",
                                AUTHOR,
                                rel,
                                n,
                            )
                        )
            touched |= mentioned
        # setup the range may not provide
        text = " ".join([m["lab"]] + [str(s.get("action") or "") for s in steps if isinstance(s, dict)])
        marked = [x.strip() for x in NRS_MARKER.findall(setups.get(n, ""))]
        for item in marked:
            needs.append({"module": n, "template": template, "item": item})
            out_f.append(
                finding(
                    "lab.needs_range_support",
                    ADVISORY,
                    f"module {n}: the range must be changed to provide: {item}",
                    PACK_AUTHOR,
                    rel,
                    n,
                )
            )
        for label, pattern, stem in SETUP_NEEDS:
            if pattern.search(text) and not any(stem.search(x) for x in marked):
                out_f.append(
                    finding(
                        "lab.range_support_unmarked",
                        HUMAN,
                        f"module {n}: the lab assumes a {label} ({pattern.search(text).group(0)!r}); confirm template {template!r} provides it, or list it in the pack's lab_setup as 'needs range support: ...'",
                        PACK_AUTHOR,
                        rel,
                        n,
                    )
                )
    ledger.ran(
        "lab.hosts_in_template",
        "harness",
        "every host a lab step lists, and every host-shaped word in its action, is a node of the named range template",
    )
    ledger.ran(
        "lab.host_used", "harness", "every host a step lists is touched by that step's action text or an earlier step's"
    )
    if pack_doc is None:
        ledger.not_run("lab.needs_range_support", "harness", "no readable instructor pack: lab_setup could not be read")
    else:
        ledger.ran(
            "lab.needs_range_support",
            "harness",
            "setup the range does not provide is marked 'needs range support' in the pack's lab_setup (advisory, never fails the course)",
        )
    return out_f, {t: sorted(h) for t, h in sorted(verified.items())}, needs


# ── instructor pack checks ───────────────────────────────────────────────


def run_pack(
    pack: Path | None, doc: dict[str, Any], parsed: dict[str, Any], ledger: Ledger
) -> tuple[list[dict[str, Any]], dict[str, Any] | None]:
    out_f: list[dict[str, Any]] = []
    name = pack.name if pack else "instructor pack"

    def bad(check: str, message: str, severity: str = FAIL, module: int | None = None) -> None:
        out_f.append(finding(check, severity, message, PACK_AUTHOR, name, module))

    if pack is None or not pack.is_file():
        bad("taz.instructor", f"no instructor pack at {pack}" if pack else "no instructor pack found")
        ledger.ran("taz.instructor", "taz-kit", "the instructor pack exists")
        for cid in ("pack.answer_key_matches_quiz", "pack.timings_match"):
            ledger.not_run(cid, "harness", "no instructor pack")
        return out_f, None
    try:
        pack_doc = _load(pack)
    except yaml.YAMLError as exc:
        bad("taz.instructor", f"not YAML: {exc}")
        ledger.ran("taz.instructor", "taz-kit", "the instructor pack parses")
        for cid in ("pack.answer_key_matches_quiz", "pack.timings_match"):
            ledger.not_run(cid, "harness", "the instructor pack is not valid YAML")
        return out_f, None
    problems = cc._schema_errors(cc.PACK_SCHEMA, pack_doc)
    if not problems and isinstance(pack_doc, dict):
        if pack_doc.get("course_code") != doc.get("course_code"):
            problems.append(f"course_code {pack_doc.get('course_code')!r} != the course's {doc.get('course_code')!r}")
        ordinals = sorted(m["ordinal"] for m in parsed["modules"])
        for key in ("timings", "answer_key_notes", "lab_setup"):
            got = sorted(e["module"] for e in pack_doc[key])
            if got != ordinals:
                problems.append(f"{key} covers modules {got}, expected one entry for each of {ordinals}")
    ledger.ran(
        "taz.instructor",
        "taz-kit",
        "the pack validates against course-instructor-pack.schema.json, names the course and covers every module",
    )
    for p in problems:
        bad("taz.instructor", p, module=_module_of(p))
    if problems and not isinstance(pack_doc, dict):
        ledger.not_run("pack.answer_key_matches_quiz", "harness", "the pack is not a mapping")
        return out_f, None

    notes: dict[int, str] = {}
    for e in pack_doc.get("answer_key_notes") or []:
        if isinstance(e, dict) and isinstance(e.get("module"), int):
            notes[e["module"]] = f"{notes.get(e['module'], '')} {e.get('notes') or ''}"
    for m in parsed["modules"]:
        n = m["ordinal"]
        if not m["questions"]:
            continue
        cited: dict[int, set[str]] = {}
        for q, letter in ANSWER_CITE.findall(notes.get(n, "")):
            cited.setdefault(int(q), set()).add(letter)
        for qi, q in enumerate(m["questions"], start=1):
            key = "".join("ABCD"[i] for i in q["correct"]) if q["correct"] else ""
            got = cited.get(qi)
            if not got:
                bad(
                    "pack.answer_key_matches_quiz",
                    f"module {n}: the answer-key notes do not cite question {qi} (key {key or '?'})",
                    module=n,
                )
            elif got != {key}:
                bad(
                    "pack.answer_key_matches_quiz",
                    f"module {n}: question {qi} is keyed {key or '?'} in the quiz but the notes say {', '.join(sorted(got))}",
                    module=n,
                )
        for qi in sorted(set(cited) - set(range(1, len(m["questions"]) + 1))):
            bad(
                "pack.answer_key_matches_quiz",
                f"module {n}: the notes cite question {qi}, but the quiz has {len(m['questions'])}",
                module=n,
            )
    ledger.ran(
        "pack.answer_key_matches_quiz",
        "harness",
        "every quiz question is cited in the pack's answer-key notes with the letter the quiz keys",
    )

    mins = {m["ordinal"]: m["duration_minutes"] for m in parsed["modules"]}
    for e in pack_doc.get("timings") or []:
        if isinstance(e, dict) and e.get("module") in mins and e.get("minutes") != mins[e["module"]]:
            bad(
                "pack.timings_match",
                f"module {e['module']}: pack timing is {e.get('minutes')} minutes, the module is {mins[e['module']]}",
                ADVISORY,
                e["module"],
            )
    ledger.ran("pack.timings_match", "harness", "pack timings equal each module's duration_minutes (advisory)")
    return out_f, pack_doc


# ── content agreement ────────────────────────────────────────────────────


def run_content(parsed: dict[str, Any], rel: str, ledger: Ledger) -> list[dict[str, Any]]:
    out_f = []
    for m in parsed["modules"]:
        if m["questions"] and m["quiz_pass"] != m["pass_threshold"]:
            out_f.append(
                finding(
                    "content.pass_threshold_agrees",
                    FAIL,
                    f"module {m['ordinal']}: pass_threshold {m['pass_threshold']} != its quiz's {m['quiz_pass']} (the cmi5 masteryScore would disagree)",
                    AUTHOR,
                    rel,
                    m["ordinal"],
                )
            )
    ledger.ran(
        "content.pass_threshold_agrees",
        "harness",
        "module pass_threshold equals its quiz's (ARC²'s cmi5.mastery_score at source)",
    )
    return out_f


# ── the run ──────────────────────────────────────────────────────────────


def qa_course(
    course: Path,
    pack: Path | None = None,
    out: Path | None = None,
    root: Path = ROOT,
    held: bool = True,
    catalogue_code: str | None = None,
) -> dict[str, Any]:
    """Run every check, write 06-qa/report.md and report.json under ``out``, return the report dict."""
    course = course.resolve()
    pack = pack.resolve() if pack else course.parent / "instructor" / course.name
    out = (out or DEFAULT_OUT / course.stem).resolve()
    out.mkdir(parents=True, exist_ok=True)
    ledger = Ledger()
    findings: list[dict[str, Any]] = []
    text = course.read_text(encoding="utf-8")
    rel = f"02-content/{course.name}"

    try:
        doc = yaml.safe_load(text)
        if not isinstance(doc, dict):
            raise ValueError("not a YAML mapping")
        api, why = arc2_qa._api()
        if api is None:
            raise ValueError(f"the API parsers could not be imported ({why})")
        parsed = api["course"].parse_course_content(text)
    except (yaml.YAMLError, ValueError, TypeError) as exc:
        findings.append(finding("qa.course_parse", FAIL, f"{rel}: {exc}", AUTHOR, rel))
        ledger.ran("qa.course_parse", "arc2", "the course file parses with the API's own parser")
        report = _report(course, pack, out, None, findings, ledger, {}, [], None, {})
        _write(out, report)
        return report

    code = catalogue_code or catalogue_code_for(root, course, parsed["course_code"])
    manifest = adapt(course, pack, out, parsed, code, root)
    findings += run_arc2(out, manifest, doc, parsed, root, ledger)
    findings += run_taz(course, root, doc, text, pack, held, ledger)
    pack_f, pack_doc = run_pack(pack, doc, parsed, ledger)
    findings += pack_f
    lab_f, verified, needs = run_lab(parsed, root, pack_doc, rel, ledger)
    findings += lab_f
    findings += run_content(parsed, rel, ledger)
    report = _report(course, pack, out, parsed, findings, ledger, verified, needs, doc, manifest)
    _write(out, report)
    return report


def _covers(check_id: str, finding_check: str) -> bool:
    for part in check_id.split(" / "):
        if part.endswith("*"):
            if finding_check.startswith(part[:-1].rstrip(".")):
                return True
        elif finding_check == part:
            return True
    return False


def _fail_counts(findings: list[dict[str, Any]], ledger: Ledger) -> None:
    for row in ledger.rows.values():
        row["fail_count"] = sum(1 for f in findings if f["severity"] == FAIL and _covers(row["id"], f["check"]))


def _report(
    course: Path,
    pack: Path | None,
    out: Path,
    parsed: dict[str, Any] | None,
    findings: list[dict[str, Any]],
    ledger: Ledger,
    verified: dict[str, list[str]],
    needs: list[dict[str, Any]],
    doc: dict[str, Any] | None,
    manifest: dict[str, Any],
) -> dict[str, Any]:
    _fail_counts(findings, ledger)
    order = {FAIL: 0, HUMAN: 1, ADVISORY: 2}
    findings = sorted(findings, key=lambda f: order[f["severity"]])
    blocking = [f for f in findings if f["severity"] == FAIL]
    actions = [
        {
            "id": f"{f['check']}:{f['message'][:60]}",
            "category": "infra" if f["check"].startswith("lab.") else "qa",
            "text": f["message"],
            "blocks_promotion": True,
            "status": "open",
            "ask": "confirm or supply",
        }
        for f in findings
        if f["severity"] == HUMAN
    ]
    actions += [
        {
            "id": f"needs_range_support:{n['template']}:{n['module']}",
            "category": "infra",
            "text": f"module {n['module']} ({n['template']}): needs range support: {n['item']}",
            "blocks_promotion": True,
            "status": "open",
            "ask": "file a range ticket",
        }
        for n in needs
    ]
    readiness = (doc or {}).get("readiness") or "draft"
    if readiness != "sme_signed":
        actions.append(
            {
                "id": "signoff",
                "category": "standards",
                "text": f"readiness is {readiness!r}: Standards and an SME have not signed this course off; QA here does not replace that",
                "blocks_promotion": True,
                "status": "open",
                "ask": "decide",
            }
        )
    modules = []
    objectives = []
    if parsed:
        module_fail: dict[int, list[str]] = {}
        for f in blocking:
            if f.get("module"):
                module_fail.setdefault(f["module"], []).append(f["check"])
        by_id = {}
        for mm in (manifest.get("content") or {}).get("modules") or []:
            by_id[mm["ordinal"]] = mm
        for m in parsed["modules"]:
            lr = m["lab_range"] or {}
            modules.append(
                {
                    "ordinal": m["ordinal"],
                    "id": by_id[m["ordinal"]]["id"],
                    "title": m["title"],
                    "objectives": len(m["objectives"]),
                    "quiz_questions": len(m["questions"]),
                    "activity": m["activity"],
                    "lab_template": lr.get("template"),
                    "lab_scenario": lr.get("scenario"),
                    "lab_steps": len(lr.get("steps") or []),
                }
            )
            for oid, t in zip(by_id[m["ordinal"]]["objective_ids"], m["objectives"], strict=False):
                named = sorted({f["check"] for f in blocking if oid in f["message"]})
                fails = sorted(set(named) | set(module_fail.get(m["ordinal"], [])))
                objectives.append(
                    {
                        "id": oid,
                        "module": m["ordinal"],
                        "text": str(t).strip(),
                        "verdict": "FAIL" if fails else "PASS",
                        "failing_checks": fails,
                        "content": f"02-content/{course.name} (module {m['ordinal']})",
                        "validators": NA_TAZ,
                        "injects": NA_TAZ,
                        "lab": f"{lr.get('template')}: {len(lr.get('steps') or [])} steps"
                        if lr
                        else "none (no lab_range)",
                    }
                )
    return {
        "schema": REPORT_SCHEMA,
        "course": {
            "file": course.name,
            "code": (parsed or {}).get("course_code"),
            "catalogue_code": (manifest.get("course") or {}).get("catalogue_code"),
            "title": (parsed or {}).get("title"),
            "readiness": readiness,
            "pack": pack.name if pack and pack.is_file() else None,
        },
        "result": "fail" if blocking else "pass",
        "counts": {
            "blocking": len(blocking),
            "human": sum(1 for f in findings if f["severity"] == HUMAN),
            "advisory": sum(1 for f in findings if f["severity"] == ADVISORY),
            "open_human_actions": len(actions),
            "needs_range_support": len(needs),
            "checks_ran": sum(1 for r in ledger.rows.values() if r["status"] == "ran"),
            "checks_not_applicable": sum(1 for r in ledger.rows.values() if r["status"] == "not_applicable"),
            "checks_not_run": sum(1 for r in ledger.rows.values() if r["status"] == "not_run"),
        },
        "modules": modules,
        "objectives": objectives,
        "findings": findings,
        "human_actions": actions,
        "needs_range_support": needs,
        "lab_hosts_verified": verified,
        "checks": list(ledger.rows.values()),
        "out": str(out),
    }


# ── report.md (ARC²'s format) ────────────────────────────────────────────


def _cell(s: Any) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def render_markdown(r: dict[str, Any]) -> str:
    c, n = r["course"], r["counts"]
    lines = [f"# ARC² QA report: {c['code'] or c['file']} {c['title'] or ''}".rstrip(), ""]
    lines += [
        "Existing course run through ARC²'s QA code (`tools/arc2/check.py`, `qa.py`), no model call. See `docs/arc2-qa-existing-courses.md`.",
        "",
    ]
    lines += ["## Preview digest", ""]
    lines += [
        f"- Course: `{c['code']}` {c['title']} (file `{c['file']}`, catalogue `{c['catalogue_code']}`, readiness `{c['readiness']}`)"
    ]
    lines += [f"- Instructor pack: `{c['pack']}`" if c["pack"] else "- Instructor pack: none found"]
    lines += [
        "",
        "| Module | Title | Objectives | Quiz | Activity | Lab template | Lab steps |",
        "|---|---|---|---|---|---|---|",
    ]
    for m in r["modules"]:
        lines += [
            f"| {m['id']} | {_cell(m['title'])} | {m['objectives']} | {m['quiz_questions'] or 'no quiz'} | {m['activity']} | {m['lab_template'] or 'none'} | {m['lab_steps']} |"
        ]
    lines += [
        "",
        "- Range: lab hosts verified against the template: "
        + (", ".join(f"`{t}`: {', '.join(h)}" for t, h in r["lab_hosts_verified"].items()) or "none (no lab_range)"),
    ]
    lines += [f"- Injects: {NA_TAZ}", f"- Critical events: {NA_TAZ}"]
    lines += [
        f"- QA: result `{r['result']}`; {n['blocking']} blocking, {n['human']} human, {n['advisory']} advisory; cycle {NA_TAZ}",
        "",
    ]
    lines += [
        "## Objectives",
        "",
        "| Objective | Text | Verdict | Content | Validators | Injects | Lab | Failing checks |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for o in r["objectives"]:
        lines += [
            f"| {o['id']} | {_cell(o['text'])} | {o['verdict']} | {_cell(o['content'])} | {o['validators']} | {o['injects']} | {_cell(o['lab'])} | {_cell(', '.join(o['failing_checks']) or '-')} |"
        ]
    lines += ["", "## Findings", ""]
    if r["findings"]:
        lines += ["| check | severity | owner_stage | message | path |", "|---|---|---|---|---|"]
        lines += [
            f"| {f['check']} | {f['severity']} | {f['owner_stage']} | {_cell(f['message'])} | {f['path'] or ''} |"
            for f in r["findings"]
        ]
    else:
        lines += ["None."]
    lines += ["", "## Human actions", ""]
    if r["human_actions"]:
        lines += ["| category | text | blocks_promotion | ask |", "|---|---|---|---|"]
        lines += [
            f"| {a['category']} | {_cell(a['text'])} | {str(a['blocks_promotion']).lower()} | {a['ask']} |"
            for a in r["human_actions"]
        ]
    else:
        lines += ["None open."]
    lines += ["", "## Verdict", "", f"`qa.result`: **{r['result']}**."]
    if r["result"] == "fail":
        lines += [
            "Fix the `fail` findings in the course file (course-author) or the instructor pack (pack-author), then run this again. ARC² stage routing and the three-cycle budget do not apply to an existing course."
        ]
    lines += [
        "",
        "## Checks",
        "",
        "`ran` = executed here; `not_applicable` = the artefact does not exist in a TAZ course (reason given); `not_run` = applies but could not run.",
        "",
    ]
    lines += ["| check | source | status | failures | detail |", "|---|---|---|---|---|"]
    order = {"ran": 0, "not_run": 1, "not_applicable": 2}
    for row in sorted(r["checks"], key=lambda x: (order[x["status"]], x["source"], x["id"])):
        lines += [
            f"| `{row['id']}` | {row['source']} | {row['status']} | {row.get('fail_count', 0) if row['status'] == 'ran' else '-'} | {_cell(row['reason'])} |"
        ]
    lines += ["", "## Needs range support", ""]
    if r["needs_range_support"]:
        lines += [
            "Setup the instructor pack says the range does not yet provide. Not a failure; file a range ticket.",
            "",
        ]
        lines += [f"- module {x['module']} (`{x['template']}`): {x['item']}" for x in r["needs_range_support"]]
    else:
        lines += ["None listed."]
    return "\n".join(lines) + "\n"


def _write(out: Path, report: dict[str, Any]) -> None:
    qa_dir = out / "06-qa"
    qa_dir.mkdir(parents=True, exist_ok=True)
    (qa_dir / "report.json").write_text(json.dumps(report, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    if report.get("modules") is not None and report["course"]["code"]:
        (qa_dir / "report.md").write_text(render_markdown(report), encoding="utf-8")
    else:
        body = "\n".join(f"- {f['check']}: {f['message']}" for f in report["findings"])
        (qa_dir / "report.md").write_text(
            f"# ARC² QA report: {report['course']['file']}\n\nresult: **fail**\n\n{body}\n", encoding="utf-8"
        )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Run ARC²'s QA stage over an existing course file and its instructor pack."
    )
    ap.add_argument("course", type=Path, help="content/courses/<file>.yaml")
    ap.add_argument(
        "--pack", type=Path, default=None, help="instructor pack (default: content/courses/instructor/<same file name>)"
    )
    ap.add_argument(
        "--out", type=Path, default=None, help=f"staging and report directory (default: {DEFAULT_OUT}/<course stem>)"
    )
    ap.add_argument("--root", type=Path, default=ROOT, help="repository root holding content/ (default: this repo)")
    ap.add_argument(
        "--catalogue-code",
        default=None,
        help="catalogue code, when it is neither in the production register nor the course_code",
    )
    ap.add_argument(
        "--no-held", dest="held", action="store_false", help="do not refuse the seven courses held for cleared authors"
    )
    args = ap.parse_args(argv)
    if not args.course.is_file():
        print(f"no such course file: {args.course}", file=sys.stderr)
        return 2
    report = qa_course(args.course, args.pack, args.out, args.root.resolve(), args.held, args.catalogue_code)
    n = report["counts"]
    print(
        f"{report['result'].upper()} {args.course.name}: {n['blocking']} blocking, {n['human']} human, {n['advisory']} advisory; "
        f"checks ran {n['checks_ran']}, not applicable {n['checks_not_applicable']}, not run {n['checks_not_run']}"
    )
    print(f"report: {report['out']}/06-qa/report.md")
    return 1 if report["result"] == "fail" else 0


if __name__ == "__main__":
    sys.exit(main())
