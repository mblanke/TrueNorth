#!/usr/bin/env python3
"""Generate the worker's copy of the content clock's rules (ADR 0014, issue #286).

``control-plane/api/app/content_review/staleness.py`` is the source; the worker's hourly sync
(``worker/content_review_sync.py``) cannot import the API (ADR 0002 §5), so it gets this
copy, under a header that says so, in ``worker/content_review_runtime/staleness.py``.

    python scripts/export_content_staleness.py          # regenerate
    python scripts/export_content_staleness.py --check  # fail on drift (tests/contracts)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "control-plane/api/app/content_review/staleness.py"
OUT = ROOT / "control-plane/worker/worker/content_review_runtime/staleness.py"
HEADER = ("# GENERATED by scripts/export_content_staleness.py from control-plane/api/app/content_review/"
          "staleness.py. Do not edit.\n")


def render() -> str:
    return HEADER + SOURCE.read_text(encoding="utf-8")


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/export_content_staleness.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
